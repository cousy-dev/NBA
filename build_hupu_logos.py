"""一次性生成 web/data/hupu_team_logos.js：拉取虎扑 API 的 NBA 球队 logoLink + teamId 映射。
   后续如需更新（赛季/logoLink 变化），重跑此脚本即可。"""
import urllib.request, json, urllib.parse, sys, os

def get(url):
    req = urllib.request.Request(url, headers={'User-Agent':'colorbox-basketball-modeling-dataset/1.0'})
    with urllib.request.urlopen(req, timeout=15) as r:
        body = json.loads(r.read().decode('utf-8'))
        if not (body.get('success') is True or body.get('status') == 200):
            raise RuntimeError(f'API failed: {url} -> {body}')
        return body.get('result')

# 与 web/data/teams.js 同步的 30 队 abbr -> nameCn 映射
teams_js = [
    ('SAS','马刺'),('POR','开拓者'),('ATL','老鹰'),('ORL','魔术'),('DET','活塞'),
    ('CHI','公牛'),('MIN','森林狼'),('GSW','勇士'),('PHX','太阳'),('WAS','奇才'),
    ('DEN','掘金'),('SAC','国王'),('DAL','独行侠'),('OKC','雷霆'),('IND','步行者'),
    ('NOP','鹈鹕'),('PHI','76人'),('BKN','篮网'),('BOS','凯尔特人'),('LAL','湖人'),
    ('MIA','热火'),('MIL','雄鹿'),('CHA','黄蜂'),('NYK','尼克斯'),('CLE','骑士'),
    ('MEM','灰熊'),('LAC','快船'),('HOU','火箭'),('TOR','猛龙'),('UTA','爵士')
]
name_to_abbr = {n: a for a, n in teams_js}

ss = get('https://games.mobileapi.hupu.com/3/8.2.62/basketballapi/switchableRankSeasonList?clientId=0&rankType=NBA_PLAYER_RANK&offline=json')
season = [s for s in ss['seasonData'] if s.get('seasonType') == 'REGULAR'][0]['season']
print(f'[build] season = {season}')
sl = get(f'https://games.mobileapi.hupu.com/3/8.2.62/basketballapi/teamStandingList?competitionLeagueType=nba&competitionType=nba&season={urllib.parse.quote(season)}&competitionStageType=REGULAR')
rm = sl.get('rankTypeListMap', {})
teams = [t for v in rm.values() for t in v]
unique = {}
for t in teams:
    unique[str(t['teamId'])] = t
print(f'[build] teams from API = {len(unique)}')

result = {}
missing = []
for tid, t in unique.items():
    name = t.get('teamShortName') or t.get('teamName')
    abbr = name_to_abbr.get(name)
    if not abbr:
        missing.append(name)
        continue
    result[abbr] = {'teamId': tid, 'logo': t.get('logoLink')}
print(f'[build] matched = {len(result)}, missing = {missing}')
if missing:
    print('[build] ERROR: 未匹配的球队中文名，请核对 teams.js 与 API 返回', file=sys.stderr)
    sys.exit(1)

out_path = os.path.join(os.path.dirname(__file__), 'web', 'data', 'hupu_team_logos.js')
lines = []
lines.append('/* Auto-generated by build_hupu_logos.py —— 虎扑 basketballapi teamStandingList 拉取的 NBA 球队 logoLink + teamId 映射。')
lines.append(f'   拉取赛季: {season}')
lines.append('   logoLink 来源: 虎扑 i11.hoopchina.com.cn CDN，虎扑 App / Shaper 平台官方球队 LOGO。')
lines.append('   再生成: 重跑 build_hupu_logos.py（脚本不进 H5，只更新静态映射表） */')
lines.append('window.HUPU_TEAM_LOGOS = {')
for abbr in sorted(result.keys()):
    info = result[abbr]
    lines.append(f"  {abbr}: {{ teamId: '{info['teamId']}', logo: '{info['logo']}' }},")
lines.append('};')
content = '\n'.join(lines) + '\n'
with open(out_path, 'w', encoding='utf-8') as f:
    f.write(content)
print(f'[build] wrote {out_path} ({len(content)} bytes)')
